CREATE SCHEMA IF NOT EXISTS enfermeria_g02;
SET search_path TO enfermeria_g02;

-- ---------------------------------------------------------------------
-- PARTE A · Modelo histórico
-- ---------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS estudiante (
  id_estudiante     BIGINT PRIMARY KEY,
  nombre_referencia VARCHAR(120) NOT NULL
);

CREATE TABLE IF NOT EXISTS practica (
  id_practica BIGINT PRIMARY KEY,
  nombre      VARCHAR(120) NOT NULL
);

CREATE TABLE IF NOT EXISTS planificacion (
  id_planificacion BIGINT PRIMARY KEY,
  id_estudiante    BIGINT NOT NULL REFERENCES estudiante(id_estudiante),
  id_practica      BIGINT NOT NULL REFERENCES practica(id_practica),
  fecha_vigente    DATE   NOT NULL
);
-- CAM-12-01: índice único auxiliar (superconjunto de la PK) para poder referenciar (planificación, estudiante) con FK compuesta.
CREATE UNIQUE INDEX IF NOT EXISTS planificacion_id_estudiante_uq ON planificacion (id_planificacion, id_estudiante);

CREATE TABLE IF NOT EXISTS institucion_practica (
  id_institucion BIGINT PRIMARY KEY,
  nombre         VARCHAR(150) NOT NULL
);

CREATE TABLE IF NOT EXISTS servicio (
  id_servicio    BIGINT PRIMARY KEY,
  id_institucion BIGINT NOT NULL REFERENCES institucion_practica(id_institucion),
  nombre         VARCHAR(120) NOT NULL
);

CREATE TABLE IF NOT EXISTS asignacion (
  id_asignacion      BIGINT PRIMARY KEY,
  id_planificacion   BIGINT NOT NULL REFERENCES planificacion(id_planificacion),
  id_servicio        BIGINT NOT NULL REFERENCES servicio(id_servicio),
  fecha_confirmacion DATE
);

CREATE TABLE IF NOT EXISTS docente_tutor (
  id_tutor          BIGINT PRIMARY KEY,
  nombre_referencia VARCHAR(120) NOT NULL
);

CREATE TABLE IF NOT EXISTS validacion_practica (
  id_validacion         BIGINT PRIMARY KEY,
  id_planificacion      BIGINT NOT NULL REFERENCES planificacion(id_planificacion),
  id_tutor              BIGINT NOT NULL REFERENCES docente_tutor(id_tutor),
  fecha_hora_validacion TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

-- ---------------------------------------------------------------------
-- PARTE B · CAM-12-01
-- Motivo: el TPA12 exige persistir el recorrido estudiante -> tutor ->
-- estudiante (creación del registro, envío, revisión, observación y
-- consulta posterior). El modelo previo no tenía cuentas, registro creado
-- por el estudiante, estado ni observación del tutor.
-- ---------------------------------------------------------------------

-- B.1 Cuentas. Una cuenta pertenece a UN estudiante o a UN tutor (nunca ambos).
CREATE TABLE IF NOT EXISTS usuario (
  id_usuario    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  username      VARCHAR(50)  NOT NULL,
  password_hash VARCHAR(100) NOT NULL,            -- bcrypt, nunca texto plano
  rol           VARCHAR(10)  NOT NULL CHECK (rol IN ('ESTUDIANTE','TUTOR')),
  id_estudiante BIGINT UNIQUE REFERENCES estudiante(id_estudiante),
  id_tutor      BIGINT UNIQUE REFERENCES docente_tutor(id_tutor),
  activo        BOOLEAN NOT NULL DEFAULT TRUE,
  CONSTRAINT usuario_rol_coherente CHECK (
    (rol = 'ESTUDIANTE' AND id_estudiante IS NOT NULL AND id_tutor IS NULL) OR
    (rol = 'TUTOR'      AND id_tutor      IS NOT NULL AND id_estudiante IS NULL)
  )
);
CREATE UNIQUE INDEX IF NOT EXISTS usuario_username_uq ON usuario (lower(username));

-- B.2 Registro de práctica creado por el estudiante.
-- Sin datos clínicos: nada de pacientes, diagnósticos ni historias clínicas.
-- La fecha de la práctica se obtiene de planificacion.fecha_vigente (no se duplica).
CREATE TABLE IF NOT EXISTS registro_practica (
  id_registro        BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_estudiante      BIGINT NOT NULL REFERENCES estudiante(id_estudiante),
  id_planificacion   BIGINT NOT NULL UNIQUE,                  -- 1 registro por planificación
  horas_realizadas   NUMERIC(4,1) CHECK (horas_realizadas >= 0.5 AND horas_realizadas <= 24 AND horas_realizadas * 2 = round(horas_realizadas * 2)), -- múltiplos de 0,5
  actividades        TEXT         CHECK (char_length(actividades) <= 1500),
  reflexion          TEXT         CHECK (char_length(reflexion) <= 1500),
  estado             VARCHAR(10)  NOT NULL DEFAULT 'BORRADOR'
                     CHECK (estado IN ('BORRADOR','ENVIADA','VALIDADA')),
  fecha_creacion     TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  fecha_envio        TIMESTAMP,
  fecha_modificacion TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  -- El estudiante del registro debe ser el dueño de la planificación (revisión Codex).
  CONSTRAINT registro_planificacion_del_estudiante FOREIGN KEY (id_planificacion, id_estudiante)
    REFERENCES planificacion (id_planificacion, id_estudiante),
  CONSTRAINT registro_id_planificacion_uq UNIQUE (id_registro, id_planificacion),
  -- Un registro enviado/validado debe estar completo y tener fecha de envío.
  CONSTRAINT registro_completo_al_enviar CHECK (
    estado = 'BORRADOR' OR
    (horas_realizadas IS NOT NULL AND actividades IS NOT NULL AND fecha_envio IS NOT NULL)
  )
);
CREATE INDEX IF NOT EXISTS registro_estudiante_idx ON registro_practica (id_estudiante);
CREATE INDEX IF NOT EXISTS registro_estado_idx     ON registro_practica (estado);

-- B.3 La revisión del tutor reutiliza validacion_practica (no se crea otra tabla).
-- Se vincula al registro y se agregan observación y resultado técnico.
-- id_registro es UNIQUE: un registro solo puede validarse una vez.
-- Las filas históricas (sin registro) siguen siendo válidas: id_registro es NULL.
ALTER TABLE validacion_practica ADD COLUMN IF NOT EXISTS id_registro BIGINT UNIQUE REFERENCES registro_practica(id_registro);
ALTER TABLE validacion_practica ADD COLUMN IF NOT EXISTS observacion TEXT CHECK (char_length(observacion) <= 1000);
ALTER TABLE validacion_practica ADD COLUMN IF NOT EXISTS resultado   VARCHAR(10) NOT NULL DEFAULT 'VALIDADA' CHECK (resultado IN ('VALIDADA'));
-- Los ids históricos eran manuales; para filas nuevas se genera el id automáticamente.
DO $$
BEGIN
  IF NOT EXISTS (SELECT 1 FROM information_schema.columns
                 WHERE table_schema = 'enfermeria_g02' AND table_name = 'validacion_practica'
                   AND column_name = 'id_validacion' AND is_identity = 'YES') THEN
    ALTER TABLE enfermeria_g02.validacion_practica ALTER COLUMN id_validacion ADD GENERATED BY DEFAULT AS IDENTITY;
  END IF;
  -- La validación y su registro deben apuntar a la MISMA planificación.
  IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'validacion_registro_planificacion_fk'
                 AND conrelid = 'enfermeria_g02.validacion_practica'::regclass) THEN
    ALTER TABLE enfermeria_g02.validacion_practica
      ADD CONSTRAINT validacion_registro_planificacion_fk FOREIGN KEY (id_registro, id_planificacion)
      REFERENCES enfermeria_g02.registro_practica (id_registro, id_planificacion);
  END IF;
END $$;
-- Sincroniza la secuencia con los ids históricos ya existentes (evita colisiones de id al insertar).
SELECT setval(pg_get_serial_sequence('enfermeria_g02.validacion_practica', 'id_validacion'),
              GREATEST((SELECT COALESCE(MAX(id_validacion), 0) FROM validacion_practica), 1),
              (SELECT COUNT(*) > 0 FROM validacion_practica));
